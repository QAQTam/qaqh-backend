// ── TypeScript output model ──────────────────────────────────────────────────

#[derive(Clone, Debug)]
enum TsType {
    Number,
    Bool,
    Str,
    /// `serde_json::JsonValue` → System.Text.Json.JsonElement.
    Json,
    /// String literal type; only valid as the discriminator of a union variant.
    Literal(String),
    Ref(String, Vec<TsType>),
    Array(Box<TsType>),
    /// `{ [key in string]: V }` → Dictionary<string, V>.
    Map(Box<TsType>),
    /// Inline object literal (union variant payload or nested data).
    Inline(Vec<Field>),
    Nullable(Box<TsType>),
}

#[derive(Clone, Debug)]
struct Field {
    json_key: String,
    optional: bool,
    ty: TsType,
}

#[derive(Clone, Debug)]
enum VariantPayload {
    Fields(Vec<Field>),
    /// `{ "tag": lit } & Name` — payload fields come from the named object type.
    Ref(String),
}

#[derive(Clone, Debug)]
struct Variant {
    literal: String,
    payload: VariantPayload,
}

#[derive(Clone, Debug)]
enum Decl {
    Alias(String),
    /// `Record<symbol, never>` — unit DTO, serializes as `{}`.
    Empty,
    Enum(Vec<String>),
    Object(Vec<Field>),
    Union {
        generic: Option<String>,
        tag: String,
        variants: Vec<Variant>,
    },
    /// `{ base } & (tagged union)` — serde flatten (SessionEventFrame).
    FlattenFrame {
        base: Vec<Field>,
        tag: String,
        variants: Vec<Variant>,
    },
    /// `{ base } & { [key in string]: ... }` — serde flatten of a map
    /// (DsAccountModel) → [JsonExtensionData].
    FlattenMap { base: Vec<Field> },
}

// ── TypeScript lexer (string- and comment-aware) ─────────────────────────────

#[derive(Clone, Debug, PartialEq)]
enum Tok {
    Punct(char),
    Ident(String),
    Str(String),
}

fn lex(source: &str) -> Result<Vec<Tok>, String> {
    let mut out = Vec::new();
    let mut chars = source.chars().peekable();
    while let Some(&c) = chars.peek() {
        match c {
            ' ' | '\t' | '\r' | '\n' => {
                chars.next();
            }
            '/' => {
                chars.next();
                match chars.next() {
                    Some('/') => {
                        while let Some(&n) = chars.peek() {
                            chars.next();
                            if n == '\n' {
                                break;
                            }
                        }
                    }
                    Some('*') => loop {
                        match chars.next() {
                            Some('*') if chars.peek() == Some(&'/') => {
                                chars.next();
                                break;
                            }
                            Some(_) => {}
                            None => return Err("unterminated block comment".into()),
                        }
                    },
                    _ => return Err("unexpected '/'".into()),
                }
            }
            '"' => {
                chars.next();
                let mut s = String::new();
                loop {
                    match chars.next() {
                        Some('"') => break,
                        Some('\\') => match chars.next() {
                            Some(escaped) => {
                                s.push('\\');
                                s.push(escaped);
                            }
                            None => return Err("unterminated string literal".into()),
                        },
                        Some(ch) => s.push(ch),
                        None => return Err("unterminated string literal".into()),
                    }
                }
                out.push(Tok::Str(s));
            }
            c if c.is_ascii_alphanumeric() || c == '_' => {
                let mut s = String::new();
                while let Some(&n) = chars.peek() {
                    if n.is_ascii_alphanumeric() || n == '_' {
                        s.push(n);
                        chars.next();
                    } else {
                        break;
                    }
                }
                out.push(Tok::Ident(s));
            }
            c if " {}[]<>()|&:,;?=".contains(c) => {
                chars.next();
                out.push(Tok::Punct(c));
            }
            other => return Err(format!("unexpected character {other:?}")),
        }
    }
    Ok(out)
}

// ── TypeScript parser (the exact subset ts-rs emits) ─────────────────────────

struct Cursor {
    toks: Vec<Tok>,
    pos: usize,
}

impl Cursor {
    fn new(toks: Vec<Tok>) -> Self {
        Self { toks, pos: 0 }
    }
    fn peek(&self) -> Option<&Tok> {
        self.toks.get(self.pos)
    }
    fn next(&mut self) -> Result<Tok, String> {
        let tok = self
            .toks
            .get(self.pos)
            .cloned()
            .ok_or_else(|| "unexpected end of file".to_string())?;
        self.pos += 1;
        Ok(tok)
    }
    fn eat_punct(&mut self, c: char) -> bool {
        if matches!(self.peek(), Some(Tok::Punct(p)) if *p == c) {
            self.pos += 1;
            true
        } else {
            false
        }
    }
    fn expect_punct(&mut self, c: char) -> Result<(), String> {
        match self.next()? {
            Tok::Punct(p) if p == c => Ok(()),
            other => Err(format!("expected {c:?}, found {other:?}")),
        }
    }
    fn expect_ident(&mut self) -> Result<String, String> {
        match self.next()? {
            Tok::Ident(id) => Ok(id),
            other => Err(format!("expected identifier, found {other:?}")),
        }
    }
}

fn parse_decl(stem: &str, toks: &[Tok]) -> Result<Decl, String> {
    let mut c = Cursor::new(toks.to_vec());
    // Skip the `import type { A, B } from "./X";` header clauses.
    while c.peek() == Some(&Tok::Ident("import".into())) {
        c.next();
        c.expect_ident()?; // "type"
        c.expect_punct('{')?;
        loop {
            c.expect_ident()?;
            if c.eat_punct(',') {
                continue;
            }
            c.expect_punct('}')?;
            break;
        }
        c.expect_ident()?; // "from"
        let module = match c.next()? {
            Tok::Str(module) => module,
            other => return Err(format!("expected import module string, found {other:?}")),
        };
        if !module.starts_with('.') {
            return Err(format!("external TypeScript import: {module}"));
        }
        c.expect_punct(';')?;
    }
    let kind = c.expect_ident()?;
    let keyword = c.expect_ident()?;
    if kind != "export" || keyword != "type" {
        return Err("file does not start with `export type`".into());
    }
    let name = c.expect_ident()?;
    if name != stem {
        return Err(format!("type name {name} does not match file stem {stem}"));
    }
    let generic = if c.eat_punct('<') {
        let param = c.expect_ident()?;
        c.expect_punct('>')?;
        Some(param)
    } else {
        None
    };
    c.expect_punct('=')?;
    let decl = parse_body(&mut c, generic)?;
    c.expect_punct(';')?;
    if c.peek().is_some() {
        return Err("trailing tokens after type declaration".into());
    }
    Ok(decl)
}

fn parse_body(c: &mut Cursor, generic: Option<String>) -> Result<Decl, String> {
    match c.peek().cloned() {
        Some(Tok::Str(_)) => {
            let mut members = Vec::new();
            loop {
                match c.next()? {
                    Tok::Str(literal) => members.push(literal),
                    other => return Err(format!("expected string literal, found {other:?}")),
                }
                if !c.eat_punct('|') {
                    break;
                }
            }
            Ok(Decl::Enum(members))
        }
        Some(Tok::Ident(id)) => {
            c.next();
            match id.as_str() {
            "Record" => {
                c.expect_punct('<')?;
                let key = c.expect_ident()?;
                c.expect_punct(',')?;
                let value = c.expect_ident()?;
                c.expect_punct('>')?;
                if key != "symbol" || value != "never" {
                    return Err(format!("unsupported Record<{key}, {value}>"));
                }
                Ok(Decl::Empty)
            }
            other => Ok(Decl::Alias(other.to_owned())),
            }
        }
        Some(Tok::Punct('{')) => {
            let first_fields = parse_object(c)?;
            // Own the lookahead so later arms can mutate the cursor.
            let after: Option<char> = match c.peek() {
                None => None,
                Some(Tok::Punct(p)) => Some(*p),
                Some(other) => {
                    return Err(format!("unexpected token after object: {other:?}"));
                }
            };
            match after {
                // Decl terminator (`;`) or EOF: a plain record.
                None | Some(';') => {
                    // ts-rs degenerate case: a single-variant internally-tagged
                    // enum is emitted as a plain object whose first field is the
                    // literal discriminator (no `|` union). String literals are
                    // only valid as discriminators (see TsType::Literal), so
                    // normalize to a one-variant union — the C# polymorphic shape
                    // then matches the multi-variant case exactly.
                    if matches!(first_fields.first().map(|f| &f.ty), Some(TsType::Literal(_))) {
                        let (tag_key, first) = split_variant(first_fields)?;
                        let (tag, variants) = unify_tag(vec![(tag_key, first)], None)?;
                        Ok(Decl::Union {
                            generic,
                            tag,
                            variants,
                        })
                    } else {
                        Ok(Decl::Object(first_fields))
                    }
                }
                Some('|') => {
                    // The first variant was consumed as a plain object; the
                    // cursor sits on the `|` that precedes variant two.
                    let (tag_key, first) = split_variant(first_fields)?;
                    let mut all = vec![(tag_key, first)];
                    all.append(&mut parse_variant_list(c, None)?);
                    let (tag, variants) = unify_tag(all, None)?;
                    Ok(Decl::Union {
                        generic,
                        tag,
                        variants,
                    })
                }
                Some('&') => {
                    c.next();
                    let after_intersection: Option<char> = match c.peek() {
                        None => None,
                        Some(Tok::Punct(p)) => Some(*p),
                        Some(other) => {
                            return Err(format!(
                                "unexpected token in intersection: {other:?}"
                            ));
                        }
                    };
                    match after_intersection {
                        Some('(') => {
                            c.next();
                            if c.peek() == Some(&Tok::Punct('{'))
                                && c.toks.get(c.pos + 1) == Some(&Tok::Punct('['))
                            {
                                // `& ({ [key in string]: ... })` — serde flatten
                                // of a map: emitted as [JsonExtensionData].
                                parse_flatten_map(c)?;
                                c.expect_punct(')')?;
                                Ok(Decl::FlattenMap { base: first_fields })
                            } else {
                                c.expect_punct('{')?;
                                let (tag_key, mut first) =
                                    split_variant(parse_object_inner(c)?)?;
                                if c.eat_punct('&') {
                                    first.payload = VariantPayload::Ref(c.expect_ident()?);
                                }
                                let mut all = vec![(tag_key, first)];
                                all.append(&mut parse_variant_list(c, Some(')'))?);
                                let (tag, variants) = unify_tag(all, Some(&first_fields))?;
                                Ok(Decl::FlattenFrame {
                                    base: first_fields,
                                    tag,
                                    variants,
                                })
                            }
                        }
                        Some('{') => {
                            parse_flatten_map(c)?;
                            Ok(Decl::FlattenMap { base: first_fields })
                        }
                        other => {
                            Err(format!("unsupported intersection after object: {other:?}"))
                        }
                    }
                }
                other => Err(format!("unexpected token after object: {other:?}")),
            }
        }
        other => Err(format!("unsupported type declaration: {other:?}")),
    }
}

/// Parse `| { variant } | { variant }` until the terminator (end of body or `)`).
fn parse_variant_list(
    c: &mut Cursor,
    terminator: Option<char>,
) -> Result<Vec<(String, Variant)>, String> {
    let mut all = Vec::new();
    while c.eat_punct('|') {
        c.expect_punct('{')?;
        let (tag_key, mut variant) = split_variant(parse_object_inner(c)?)?;
        if c.eat_punct('&') {
            // `{ "tag": lit } & Name` — payload fields come from the named type.
            variant.payload = VariantPayload::Ref(c.expect_ident()?);
        }
        all.push((tag_key, variant));
    }
    if let Some(punct) = terminator {
        c.expect_punct(punct)?;
    }
    Ok(all)
}

/// Peel the string-literal discriminator field off a variant; the remaining
/// fields are its payload.
fn split_variant(fields: Vec<Field>) -> Result<(String, Variant), String> {
    let mut iter = fields.into_iter();
    let first = iter.next().ok_or("union variant has no fields")?;
    let TsType::Literal(literal) = first.ty else {
        return Err(format!(
            "variant field {:?} is not a string-literal discriminator",
            first.json_key
        ));
    };
    let tag_key = first.json_key.clone();
    Ok((
        tag_key,
        Variant {
            literal,
            payload: VariantPayload::Fields(iter.collect()),
        },
    ))
}

fn parse_object(c: &mut Cursor) -> Result<Vec<Field>, String> {
    c.expect_punct('{')?;
    parse_object_inner(c)
}

fn parse_object_inner(c: &mut Cursor) -> Result<Vec<Field>, String> {
    let mut fields = Vec::new();
    loop {
        if c.eat_punct('}') {
            return Ok(fields);
        }
        let json_key = match c.next()? {
            Tok::Ident(id) => id,
            Tok::Str(s) => s,
            other => return Err(format!("expected property name, found {other:?}")),
        };
        let optional = c.eat_punct('?');
        c.expect_punct(':')?;
        let ty = parse_type(c)?;
        fields.push(Field {
            json_key,
            optional,
            ty,
        });
        if c.eat_punct(',') {
            continue;
        }
        c.expect_punct('}')?;
        return Ok(fields);
    }
}

fn parse_type(c: &mut Cursor) -> Result<TsType, String> {
    let base = match c.next()? {
        Tok::Str(literal) => TsType::Literal(literal),
        Tok::Ident(id) => match id.as_str() {
            "string" => TsType::Str,
            "number" => TsType::Number,
            "boolean" => TsType::Bool,
            "JsonValue" => TsType::Json,
            "Array" => {
                c.expect_punct('<')?;
                let element = parse_type(c)?;
                c.expect_punct('>')?;
                TsType::Array(Box::new(element))
            }
            "Record" => return Err("Record<> is only supported at declaration level".into()),
            "null" => return Err("bare null is not a supported field type".into()),
            other => {
                let mut args = Vec::new();
                if c.eat_punct('<') {
                    loop {
                        args.push(parse_type(c)?);
                        if c.eat_punct(',') {
                            continue;
                        }
                        c.expect_punct('>')?;
                        break;
                    }
                }
                TsType::Ref(other.to_owned(), args)
            }
        },
        Tok::Punct('{') => {
            if c.eat_punct('[') {
                c.expect_ident()?;
                let keyword = c.expect_ident()?;
                let source = c.expect_ident()?;
                if keyword != "in" || source != "string" {
                    return Err("expected `[key in string]` index signature".into());
                }
                c.expect_punct(']')?;
                c.expect_punct(':')?;
                let value = parse_type(c)?;
                c.expect_punct('}')?;
                TsType::Map(Box::new(value))
            } else {
                TsType::Inline(parse_object_inner(c)?)
            }
        }
        other => return Err(format!("unsupported field type: {other:?}")),
    };
    let mut ty = base;
    while c.eat_punct('|') {
        let rhs = c.expect_ident()?;
        if rhs != "null" {
            return Err(format!("unsupported union member {rhs:?} in field position"));
        }
        ty = TsType::Nullable(Box::new(ty));
    }
    Ok(ty)
}

/// Parse the `{ [key in string]: ... }` half of a flatten-map intersection.
/// The value type is emitted as [JsonExtensionData] regardless of its shape.
fn parse_flatten_map(c: &mut Cursor) -> Result<(), String> {
    c.expect_punct('{')?;
    c.expect_punct('[')?;
    c.expect_ident()?;
    let keyword = c.expect_ident()?;
    let source = c.expect_ident()?;
    if keyword != "in" || source != "string" {
        return Err("expected `[key in string]` index signature".into());
    }
    c.expect_punct(']')?;
    c.expect_punct(':')?;
    skip_balanced(c)?;
    Ok(())
}

/// Skip a balanced `{ ... }` block (used for the map half of a flatten-map
/// intersection whose value type is a primitive union; it is emitted as
/// [JsonExtensionData] regardless).
fn skip_balanced(c: &mut Cursor) -> Result<(), String> {
    let mut depth = 0usize;
    loop {
        match c.next()? {
            Tok::Punct('{') => depth += 1,
            Tok::Punct('}') => {
                if depth == 0 {
                    return Ok(());
                }
                depth -= 1;
            }
            _ => {}
        }
    }
}

/// Require one shared discriminator key across all variants; payload fields
/// and flatten-base properties must not shadow it.
fn unify_tag(
    all: Vec<(String, Variant)>,
    base: Option<&[Field]>,
) -> Result<(String, Vec<Variant>), String> {
    let mut iter = all.into_iter();
    let (tag, first) = iter.next().ok_or("union has no variants")?;
    let mut variants = vec![first];
    for (other_tag, variant) in iter {
        if other_tag != tag {
            return Err(format!(
                "inconsistent union discriminators {tag:?} vs {other_tag:?}"
            ));
        }
        variants.push(variant);
    }
    for variant in &variants {
        let VariantPayload::Fields(fields) = &variant.payload else {
            continue;
        };
        for field in fields {
            if field.json_key == tag {
                return Err(format!(
                    "variant {:?} payload field {:?} shadows the discriminator",
                    variant.literal, field.json_key
                ));
            }
        }
    }
    if let Some(base) = base {
        for field in base {
            if field.json_key == tag {
                return Err(format!(
                    "flatten base property {:?} collides with the discriminator",
                    field.json_key
                ));
            }
        }
    }
    Ok((tag, variants))
}

// ── C# emission ──────────────────────────────────────────────────────────────

struct Model {
    decls: BTreeMap<String, Decl>,
}

impl Model {
    fn decl(&self, name: &str) -> Result<&Decl, String> {
        self.decls
            .get(name)
            .ok_or_else(|| format!("unknown type reference {name}"))
    }

    /// Follow `export type X = string` alias chains; only string aliases exist.
    fn is_string_alias(&self, name: &str) -> Result<bool, String> {
        let mut current = name;
        for _ in 0..16 {
            match self.decl(current)? {
                Decl::Alias(target) if target == ALIAS_TARGET => return Ok(true),
                Decl::Alias(target) => current = target,
                _ => return Ok(false),
            }
        }
        Err(format!("alias cycle at {name}"))
    }

    fn generic_check(&self, name: &str, args: &[TsType]) -> Result<(), String> {
        let expected = match self.decl(name)? {
            Decl::Union { generic, .. } => generic.is_some(),
            _ => false,
        };
        if expected != !args.is_empty() {
            return Err(format!(
                "generic arity mismatch on reference {name} ({} args)",
                args.len()
            ));
        }
        Ok(())
    }

    fn cs_type(&self, ty: &TsType, generic: Option<&str>) -> Result<String, String> {
        Ok(match ty {
            TsType::Number => "long".into(),
            TsType::Bool => "bool".into(),
            TsType::Str => "string".into(),
            TsType::Json => "JsonElement".into(),
            TsType::Literal(_) => {
                return Err("string literal outside discriminator position".into())
            }
            TsType::Nullable(inner) => format!("{}?", self.cs_type(inner, generic)?),
            TsType::Array(element) => format!("{}[]", self.cs_type(element, generic)?),
            TsType::Map(value) => format!("Dictionary<string, {}>", self.cs_type(value, generic)?),
            TsType::Inline(_) => {
                return Err("inline object must be emitted as a named data record".into())
            }
            TsType::Ref(name, args) => {
                if Some(name.as_str()) == generic {
                    if !args.is_empty() {
                        return Err(format!("generic parameter {name} cannot take arguments"));
                    }
                    name.clone()
                } else if name == "JsonValue" {
                    "JsonElement".into()
                } else {
                    self.generic_check(name, args)?;
                    if args.is_empty() && self.is_string_alias(name)? {
                        return Ok("string".into());
                    }
                    let mut rendered = name.clone();
                    if !args.is_empty() {
                        rendered.push('<');
                        for (index, arg) in args.iter().enumerate() {
                            if index > 0 {
                                rendered.push_str(", ");
                            }
                            rendered.push_str(&self.cs_type(arg, None)?);
                        }
                        rendered.push('>');
                    }
                    rendered
                }
            }
        })
    }

    /// C# type for a property, applying the float-field rule.
    fn property_type(
        &self,
        field: &Field,
        context: &str,
        generic: Option<&str>,
    ) -> Result<String, String> {
        let is_number = match &field.ty {
            TsType::Number => true,
            TsType::Nullable(inner) => matches!(**inner, TsType::Number),
            _ => false,
        };
        if is_number
            && FLOAT_FIELDS
                .iter()
                .any(|(owner, key)| *owner == context && *key == field.json_key)
        {
            return Ok(if matches!(field.ty, TsType::Nullable(_)) {
                "double?".into()
            } else {
                "double".into()
            });
        }
        self.cs_type(&field.ty, generic)
    }

    fn emit_properties<'a>(
        &self,
        fields: &'a [Field],
        record_name: &str,
        generic: Option<&str>,
        out: &mut String,
    ) -> Result<Vec<(String, &'a [Field])>, String> {
        let mut seen: HashSet<String> = HashSet::new();
        let mut inline = Vec::new();
        for field in fields {
            let property = pascal(&field.json_key);
            if !seen.insert(property.clone()) {
                return Err(format!(
                    "properties {property:?} collide after PascalCase conversion in {record_name}"
                ));
            }
            if property == record_name {
                return Err(format!(
                    "property {property:?} cannot share its record name ({record_name})"
                ));
            }
            if field.json_key.starts_with(char::is_uppercase) {
                return Err(format!("unexpected property key {:?}", field.json_key));
            }
            let ty = match &field.ty {
                TsType::Inline(inner) => {
                    let data_name = format!("{record_name}{property}");
                    inline.push((data_name.clone(), inner.as_slice()));
                    data_name
                }
                other => self.property_type(field, record_name, generic)?,
            };
            // ts-rs 的 `?` 可选标记 = Rust 侧 skip_serializing_if：null 时整键缺席。
            // 逐字段标注（不能走全局 DefaultIgnoreCondition——无 skip 的 Option
            // 序列化时必须显式写 null，例如 workspace_id: null = 未分组）。
            if field.optional {
                out.push_str(&format!(
                    "    [JsonPropertyName(\"{}\")]\n    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]\n    public {} {} {{ get; init; }}\n",
                    field.json_key,
                    ty,
                    cs_ident(&property),
                ));
            } else {
                out.push_str(&format!(
                    "    [JsonPropertyName(\"{}\")]\n    public {} {} {{ get; init; }}\n",
                    field.json_key,
                    ty,
                    cs_ident(&property),
                ));
            }
        }
        Ok(inline)
    }

    fn emit_record(
        &self,
        name: &str,
        generic: Option<&str>,
        head: &str,
        inherits: Option<&str>,
        fields: &[Field],
        out: &mut String,
    ) -> Result<(), String> {
        let type_params = generic.map(|g| format!("<{g}>")).unwrap_or_default();
        let base = inherits.map(|base| format!(" : {base}")).unwrap_or_default();
        if fields.is_empty() {
            out.push_str(&format!("{head} {name}{type_params}{base};\n"));
            return Ok(());
        }
        out.push_str(&format!("{head} {name}{type_params}{base}\n{{\n"));
        let inline = self.emit_properties(fields, name, generic, out)?;
        out.push_str("}\n");
        for (data_name, data_fields) in inline {
            if data_fields.iter().any(|f| matches!(f.ty, TsType::Inline(_))) {
                return Err(format!("nested inline objects are not supported ({data_name})"));
            }
            out.push('\n');
            self.emit_record(
                &data_name,
                None,
                "public sealed record",
                None,
                data_fields,
                out,
            )?;
        }
        Ok(())
    }

    fn emit_type(&self, name: &str, decl: &Decl) -> Result<String, String> {
        let mut body = String::new();
        match decl {
            Decl::Alias(_) => unreachable!("alias types are not emitted"),
            Decl::Empty => {
                body.push_str(&format!("public sealed record {name};\n"));
            }
            Decl::Enum(members) => {
                let mut seen: HashSet<String> = HashSet::new();
                body.push_str(&format!("public enum {name}\n{{\n"));
                for literal in members {
                    let member = pascal(literal);
                    if !seen.insert(member.clone()) {
                        return Err(format!(
                            "enum members {member:?} collide after PascalCase conversion in {name}"
                        ));
                    }
                    body.push_str(&format!(
                        "    [JsonStringEnumMemberName(\"{literal}\")]\n    {},\n",
                        cs_ident(&member)
                    ));
                }
                body.push_str("}\n");
            }
            Decl::Object(fields) => {
                self.emit_record(
                    name,
                    None,
                    "public sealed record",
                    None,
                    fields,
                    &mut body,
                )?;
            }
            Decl::FlattenMap { base } => {
                body.push_str(&format!("public sealed record {name}\n{{\n"));
                self.emit_properties(base, name, None, &mut body)?;
                body.push_str("\n    [JsonExtensionData]\n    public Dictionary<string, JsonElement>? Extra { get; init; }\n}\n");
            }
            Decl::Union { .. } | Decl::FlattenFrame { .. } => {
                let (generic, tag, base, variants) = match decl {
                    Decl::Union {
                        generic,
                        tag,
                        variants,
                    } => (generic.clone(), tag.clone(), Vec::new(), variants),
                    Decl::FlattenFrame {
                        base,
                        tag,
                        variants,
                        ..
                    } => (None, tag.clone(), base.clone(), variants),
                    _ => unreachable!(),
                };
                let type_params = generic.as_deref().map(|g| format!("<{g}>")).unwrap_or_default();
                // System.Text.Json cannot register open generic derived types,
                // so generic unions get a hand-rolled discriminator converter
                // instead of JsonPolymorphic/JsonDerivedType.
                let mut variant_payloads = Vec::new();
                for variant in variants {
                    let variant_name = format!("{name}{}", cs_ident(&pascal(&variant.literal)));
                    let payload_fields = match &variant.payload {
                        VariantPayload::Fields(fields) => fields.clone(),
                        VariantPayload::Ref(ref_name) => {
                            if generic.is_some() {
                                return Err(
                                    "generic union variants cannot reference payload types".into()
                                );
                            }
                            match self.decl(ref_name)? {
                                Decl::Object(fields) => fields.clone(),
                                other => {
                                    return Err(format!(
                                    "variant payload reference {ref_name} is {other:?}, expected an object"
                                ))
                                }
                            }
                        }
                    };
                    if generic.is_some() {
                        for field in &payload_fields {
                            if field.optional {
                                return Err(format!(
                                    "generic union variant payload field {:?} must be required",
                                    field.json_key
                                ));
                            }
                        }
                    }
                    variant_payloads.push((variant_name, variant.literal.clone(), payload_fields));
                }
                if generic.is_some() {
                    body.push_str(&format!(
                        "[JsonConverter(typeof({name}JsonConverterFactory))]\n"
                    ));
                } else {
                    body.push_str(&format!(
                        "[JsonPolymorphic(TypeDiscriminatorPropertyName = \"{tag}\")]\n"
                    ));
                    for (variant_name, literal, _) in &variant_payloads {
                        body.push_str(&format!(
                            "[JsonDerivedType(typeof({variant_name}), \"{literal}\")]\n"
                        ));
                    }
                }
                let head = "public abstract record";
                if base.is_empty() {
                    body.push_str(&format!("{head} {name}{type_params};\n"));
                } else {
                    body.push_str(&format!("{head} {name}{type_params}\n{{\n"));
                    self.emit_properties(&base, name, generic.as_deref(), &mut body)?;
                    body.push_str("}\n");
                }
                for (variant_name, _, payload_fields) in &variant_payloads {
                    body.push('\n');
                    let inherits = format!("{name}{type_params}");
                    self.emit_record(
                        variant_name,
                        generic.as_deref(),
                        "public sealed record",
                        Some(&inherits),
                        payload_fields,
                        &mut body,
                    )?;
                }
                if let Some(param) = &generic {
                    body.push('\n');
                    self.emit_generic_union_converter(
                        name,
                        param,
                        &tag,
                        &variant_payloads,
                        &mut body,
                    )?;
                }
            }
        }
        Ok(format!("{}{}\n", header(), body))
    }

    /// Hand-rolled discriminator converter for a generic tagged union
    /// (System.Text.Json cannot register open generic derived types).
    #[allow(clippy::too_many_arguments)]
    fn emit_generic_union_converter(
        &self,
        name: &str,
        param: &str,
        tag: &str,
        variants: &[(String, String, Vec<Field>)],
        out: &mut String,
    ) -> Result<(), String> {
        out.push_str(&format!(
            "public sealed class {name}JsonConverter<{param}> : JsonConverter<{name}<{param}>>\n{{\n"
        ));
        out.push_str(&format!(
            "    public override {name}<{param}> Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)\n    {{\n        using var document = JsonDocument.ParseValue(ref reader);\n        var root = document.RootElement;\n        return root.GetProperty(\"{tag}\").GetString() switch\n        {{\n"
        ));
        for (variant_name, literal, fields) in variants {
            out.push_str(&format!(
                "            \"{literal}\" => new {variant_name}<{param}>\n            {{\n"
            ));
            for field in fields {
                out.push_str(&format!(
                    "                {0} = root.GetProperty(\"{1}\").Deserialize<{2}>(options)!,\n",
                    cs_ident(&pascal(&field.json_key)),
                    field.json_key,
                    self.property_type(field, variant_name, Some(param))?,
                ));
            }
            out.push_str("            },\n");
        }
        out.push_str(&format!(
            "            _ => throw new JsonException($\"unknown {name} discriminator\"),\n        }};\n    }}\n\n"
        ));
        out.push_str(&format!(
            "    public override void Write(Utf8JsonWriter writer, {name}<{param}> value, JsonSerializerOptions options)\n    {{\n        writer.WriteStartObject();\n        switch (value)\n        {{\n"
        ));
        for (variant_name, literal, fields) in variants {
            if fields.is_empty() {
                out.push_str(&format!(
                    "            case {variant_name}<{param}>:\n                writer.WriteString(\"{tag}\", \"{literal}\");\n                break;\n"
                ));
            } else {
                out.push_str(&format!(
                    "            case {variant_name}<{param}> casted:\n                writer.WriteString(\"{tag}\", \"{literal}\");\n"
                ));
                for field in fields {
                    out.push_str(&format!(
                        "                writer.WritePropertyName(\"{1}\");\n                JsonSerializer.Serialize(writer, casted.{0}, options);\n",
                        cs_ident(&pascal(&field.json_key)),
                        field.json_key,
                    ));
                }
                out.push_str("                break;\n");
            }
        }
        out.push_str("        }\n        writer.WriteEndObject();\n    }\n}\n");
        out.push('\n');
        out.push_str(&format!(
            "public sealed class {name}JsonConverterFactory : JsonConverterFactory\n{{\n    public override bool CanConvert(Type typeToConvert) =>\n        typeToConvert.IsGenericType && typeToConvert.GetGenericTypeDefinition() == typeof({name}<>);\n\n    public override JsonConverter? CreateConverter(Type typeToConvert, JsonSerializerOptions options) =>\n        (JsonConverter?)Activator.CreateInstance(\n            typeof({name}JsonConverter<>).MakeGenericType(typeToConvert.GetGenericArguments()));\n}}\n"
        ));
        Ok(())
    }
}

// ── deterministic name conversion ────────────────────────────────────────────

/// snake_case / kebab-case / dotted / camelCase / PascalCase JSON keys and
/// literals → PascalCase (e.g. `session.create` → `SessionCreate`).
fn pascal(key: &str) -> String {
    let mut out = String::new();
    for part in key.split(['_', '-', '.']) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.is_empty() {
        panic!("empty JSON key cannot be converted to a C# identifier");
    }
    out
}

fn cs_ident(name: &str) -> String {
    if CS_KEYWORDS.contains(&name) {
        format!("@{name}")
    } else {
        name.to_owned()
    }
}
