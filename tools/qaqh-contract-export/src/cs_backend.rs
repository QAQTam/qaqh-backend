//! C# contract emission for the pure C# consumer: parses the deterministic
//! ts-rs TypeScript output inside the staging tree and re-encodes the same
//! wire contract as System.Text.Json-ready C# types (BCL only, no external
//! dependencies). Wire JSON names round-trip exactly; every property carries
//! an explicit `[JsonPropertyName]`.

use std::collections::{BTreeMap, HashSet};
use std::fs;
use std::path::Path;

use crate::GENERATOR_VERSION;

const NAMESPACE: &str = "Qaqh.Sdk.Contract";

/// ts-rs renders every numeric as TS `number`; the contract's only float
/// fields are the auto-compact threshold (f64 in the Rust DTOs), so `number`
/// maps to `long` except for these (type, JSON key) pairs → `double`.
const FLOAT_FIELDS: &[(&str, &str)] = &[
    ("ConfigDto", "autoCompactThreshold"),
    ("ConfigPatch", "autoCompactThreshold"),
];

/// DTOs that are pure string aliases on the wire (`export type X = string`).
/// C# has no top-level aliases, so references resolve to `string` and no file
/// is emitted for them; the wire shape is unaffected.
const ALIAS_TARGET: &str = "string";

/// C# reserved words that cannot be used as member names.
